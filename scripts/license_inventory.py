"""Regenerate docs/dependency-licenses.md from uv.lock and installed package metadata.

Usage (after scripts/setup-env.ps1 for both 3.11 and 3.14):
    .venvs/py314/Scripts/python scripts/license_inventory.py

Metadata is read from every .venvs/*/Lib/site-packages, so packages locked for only
one Python version (e.g. numpy's 3.11 fork) are covered. Automated metadata is
reported as-is; only entries in REVIEWED have a human-inspected license file.
"""

from __future__ import annotations

import tomllib
from importlib.metadata import Distribution, distributions
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs/dependency-licenses.md"
PROJECT = "mambo-electricity-explorer"
DIRECT = {
    "streamlit": "runtime",
    "pyyaml": "runtime",
    "duckdb": "runtime",
    "pyarrow": "runtime",
    "pytest": "dev",
    "ruff": "dev",
}

# Human review: the license file shipped in the installed wheel was opened and read.
REVIEWED = {
    "pyyaml": "Shipped LICENSE read 2026-10-11: MIT permission text.",
    "pytest": "Shipped LICENSE read 2026-10-11: MIT License text.",
    "ruff": "Shipped LICENSE read 2026-10-11: MIT for Ruff plus bundled third-party "
    "notices (430 lines) not individually reviewed.",
    "streamlit": "UNRESOLVED: wheel ships no license file; metadata only. Upstream "
    "repository LICENSE not yet checked.",
}

SOURCE_KEYS = ("source", "source code", "repository", "github", "code", "homepage")


def _norm(name: str) -> str:
    return name.lower().replace("_", "-").replace(".", "-")


def _metadata_index() -> dict[tuple[str, str], Distribution]:
    index = {}
    for site in sorted(REPO.glob(".venvs/*/Lib/site-packages")):
        for dist in distributions(path=[str(site)]):
            index.setdefault((_norm(dist.metadata["Name"]), dist.version), dist)
    return index


def _license(dist: Distribution) -> tuple[str, bool]:
    """Return (evidence text, ambiguous?)."""
    meta = dist.metadata
    expression = meta.get("License-Expression")
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if "License" in c]
    raw = (meta.get("License") or "").strip()
    if expression:
        text = f"License-Expression: {expression}"
        ambiguous = any(t in expression for t in (" OR ", " AND ", "LicenseRef", " WITH "))
    elif classifiers:
        text = "Classifier: " + "; ".join(classifiers)
        # A bare "BSD License" classifier does not say which BSD variant applies.
        ambiguous = len(classifiers) > 1 or "BSD License" in classifiers
    elif raw and "\n" not in raw and len(raw) <= 40:
        text = f"License: {raw}"
        ambiguous = False
    else:
        text = "License field: free text or missing" if raw else "No license metadata"
        ambiguous = True
    # Copyleft-family licenses carry conditions that need a human look.
    ambiguous = ambiguous or any(t in text for t in ("MPL", "Mozilla", "GPL", "EPL", "CDDL"))
    files = meta.get_all("License-File") or []
    text += f"; license files: {len(files)}"
    return text, ambiguous


def _source(dist: Distribution) -> str:
    urls = {}
    for entry in dist.metadata.get_all("Project-URL") or []:
        label, _, url = entry.partition(",")
        urls[label.strip().lower()] = url.strip()
    for key in SOURCE_KEYS:
        if key in urls:
            return urls[key]
    return dist.metadata.get("Home-page") or f"https://pypi.org/project/{dist.metadata['Name']}/"


def main() -> None:
    lock = tomllib.loads((REPO / "uv.lock").read_text("utf-8"))
    locked = sorted({(p["name"], p["version"]) for p in lock["package"] if p["name"] != PROJECT})
    index = _metadata_index()
    rows, gaps = [], 0
    for name, version in locked:
        dist = index.get((_norm(name), version))
        role = DIRECT.get(name, "transitive")
        if dist is None:
            evidence, ambiguous, source = "NOT INSTALLED: metadata not inspected", True, "—"
        else:
            evidence, ambiguous = _license(dist)
            source = _source(dist)
        review = REVIEWED.get(name, "Not reviewed")
        unresolved = ambiguous or review.startswith("UNRESOLVED") or review == "Not reviewed"
        status = (
            "needs review (compound or unclear)"
            if ambiguous
            else ("unreviewed" if unresolved else "reviewed")
        )
        gaps += ambiguous
        rows.append(
            f"| {name} | {version} | {role} | {evidence} | {review} | {source} | {status} |"
        )

    OUT.write_text(
        "\n".join(
            [
                "# Dependency License Inventory",
                "",
                "Generated by `scripts/license_inventory.py` from `uv.lock` and installed package",
                "metadata in `.venvs/py311` and `.venvs/py314` (Windows). **Do not edit by hand.**",
                "",
                "- **Automated metadata** is what each package declares. It is not verified.",
                "- **Reviewed evidence** lists only license files a person actually read.",
                "- Nothing here certifies legal compatibility or chooses this project's license",
                "  (ADR 0001).",
                "",
                f"Locked packages: {len(rows)}. Compound, unclear, or missing metadata: {gaps}. "
                f"Reviewed: {sum(r.endswith('| reviewed |') for r in rows)}.",
                "",
                "| Package | Version | Role | Automated metadata | Reviewed evidence | "
                "Official source | Status |",
                "|---|---|---|---|---|---|---|",
                *rows,
                "",
            ]
        ),
        encoding="utf-8",
        newline="\n",
    )
    print(f"wrote {OUT.relative_to(REPO)}: {len(rows)} packages, {gaps} ambiguous")


if __name__ == "__main__":
    main()
